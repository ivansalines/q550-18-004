#!/usr/bin/env python3
"""Generate the exact symbolic RHS/Jacobian/Hessian for the pinned Q550 support model.

Source transcription: test_support_q550_support_ode_interval_residual_pilot_v1.py
and test_support_mobius_monodromy_audit.py (source SHA-pinned in README).
This generator requires SymPy; generated module requires only NumPy and math.
No original scientific model source is rewritten or patched.
"""
from pathlib import Path
import sympy as s

Y=s.symbols('y1 v1 t1 w1 y2 v2 t2 w2 z vz TH',real=True)
y1,v1,t1,w1,y2,v2,t2,w2,z,vz,TH=Y
P=s.symbols('phi0 er barrier mu gamma_x gamma_rho mass',real=True)
phi0,er,barrier,mu,gamma_x,gamma_rho,mass=P
x=1/(1+s.exp(-z));g=x*(1-x);q=2*s.pi/x
delta=t1+t2-phi0-TH
rho1=s.exp(y1);rho2=s.exp(y2)
du=lambda rho:2-s.Rational(12,5)*rho+s.Rational(4,5)*rho**2-er**2/rho**4
dV=-barrier*(1/x-1/(1-x))
base=[q*v1,
      q*(w1**2-du(rho1)-gamma_rho*v1-v1**2),
      q*w1, q*(-2*v1*w1),
      q*v2,
      q*(w2**2-du(rho2)-gamma_rho*v2-v2**2),
      q*w2,q*(-2*v2*w2),q*vz,
      q*((-dV+mu*rho1*rho2*s.sin(delta)-gamma_x*g*vz)/(mass*g)-(1-2*x)*vz**2),
      2*s.pi]
assert len(base)==11
coords=[]; expressions=[]
for i in range(11):
    if base[i]!=0:coords.append(('F',i));expressions.append(base[i])
for i in range(11):
    for j in range(11):
        e=s.diff(base[i],Y[j]);
        if e!=0:coords.append(('J',i,j));expressions.append(e)
for i in range(11):
    for j in range(11):
        for k in range(j,11):
            e=s.diff(base[i],Y[j],Y[k])
            if e!=0: coords.append(('H',i,j,k));expressions.append(e)
subs, expr=s.cse(expressions,s.numbered_symbols('_t'))
header='''#!/usr/bin/env python3
"""GENERATED by scripts/generate_structural_math.py (do not manually edit).
Exact real-arithmetic derivatives of the parameter-INDEPENDENT support RHS.
Floating-point evaluation is not an interval proof.
"""
import math
import numpy as np

def base_jet(y, params):
    """Return F(κ=0), DF(κ=0), D²F(κ=0) in the ORIGINAL 11D coordinates."""
    y=np.asarray(y,dtype=float)
    if y.shape!=(11,): raise ValueError('expected 11D state')
    y1,v1,t1,w1,y2,v2,t2,w2,z,vz,TH = (float(t) for t in y)
    phi0=float(params.phi0); er=float(params.e_reserve)
    barrier=float(params.barrier_B); mu=float(params.mu_x)
    gamma_x=float(params.gamma_x); gamma_rho=float(params.gamma_rho)
    mass=float(params.m_x)
    F=np.zeros(11); J=np.zeros((11,11)); H=np.zeros((11,11,11))
'''
out=[header]
for key,value in subs:
    out.append('    '+str(key)+' = '+s.pycode(value)+'\n')
for loc,value in zip(coords,expr):
    kind,*idx=loc; val=s.pycode(value)
    if kind=='F': line=f'    F[{idx[0]}] = {val}\n'
    elif kind=='J':line=f'    J[{idx[0]},{idx[1]}] = {val}\n'
    else:
        line=f'    H[{idx[0]},{idx[1]},{idx[2]}] = {val}\n'
        if idx[1]!=idx[2]:line+=f'    H[{idx[0]},{idx[2]},{idx[1]}] = H[{idx[0]},{idx[1]},{idx[2]}]\n'
    out.append(line)
out.append('    return F,J,H\n')
target=Path(__file__).with_name('generated_base_jet.py')
target.write_text(''.join(out),encoding='utf-8')
print('Generated',target,'expressions',len(coords),'CSE',len(subs))
